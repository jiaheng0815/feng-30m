def build() -> list[dict]:
    rng = random.Random(20261004)
    out: list[dict] = []

    for prompts, replies in GREETINGS + FAREWELLS + COURTESY:
        for p in prompts:
            for r in replies:
                out.append(conv(p, r))
    for prompts, replies in CAPABILITY:
        for p in prompts:
            for r in replies:
                out.append(conv(p, r))
    for prompts, replies in EMOTION:
        for p in prompts:
            for r in replies:
                out.append(conv(p, r))

    # 写诗：主题 × 问法
    for theme, idx in POEM_THEMES:
        out.append(conv(f"以{theme}为题写首诗", POEMS[idx]))
    for p in POEM_PROMPTS:
        for poem in POEMS:
            out.append(conv(p, poem))
    # 短故事
    for topic, story in STORIES:
        out.append(conv(f"写个关于{topic}的短故事", story))
        out.append(conv("写个短故事", story))
    for prompts, reply in WISHES:
        for p in prompts:
            out.append(conv(p, reply))
    for prompts, reply in NICKNAMES:
        for p in prompts:
            out.append(conv(p, reply))

    # 常识：每种问法组合一次
    for q, a in FACTS:
        core = q.rstrip("？?")
        forms = [q]
        if "是什么" in q or "是谁" in q or "在哪" in q:
            forms.append(core + "呢？")
        for f in forms:
            out.append(conv(f, a))

    # 数学：小数字加法/减法/乘法
    for _ in range(45):
        a, b = rng.randint(1, 9), rng.randint(1, 9)
        s = a + b
        ans = f"{a} 加 {b} 等于 {s}。"
        out.append(conv(f"{a}+{b}等于几？", ans))
        out.append(conv(f"{a}加{b}等于几？", ans))
    for _ in range(25):
        a, b = rng.randint(5, 20), rng.randint(1, 9)
        if a < b:
            a, b = b, a
        ans = f"{a} 减 {b} 等于 {a - b}。"
        out.append(conv(f"{a}-{b}等于几？", ans))
        out.append(conv(f"{a}减{b}等于几？", ans))
    for _ in range(12):
        a, b = rng.randint(2, 9), rng.randint(2, 9)
        out.append(conv(f"{a}乘{b}等于几？", f"{a} 乘 {b} 等于 {a * b}。"))

    # 翻译：词条 × 问法
    for w, t in TRANSLATE_EN:
        for f in TRANSLATE_TEMPLATES["en"]:
            out.append(conv(f.format(w=w), t))
    for w, t in TRANSLATE_JA:
        for f in TRANSLATE_TEMPLATES["ja"]:
            out.append(conv(f.format(w=w), t))

    for prompts, reply in REALTIME + SAFETY + UNCERTAIN:
        for p in prompts:
            out.append(conv(p, reply))

    rng.shuffle(out)
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "archive" / "v3_6a" / "daily_patch.jsonl"))
    args = ap.parse_args()
    rows = build()
    dest = Path(args.out)
    dest.parent.mkdir(parents=True, exist_ok=True)
    with dest.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"日常对话补丁：{len(rows)} 条 -> {dest}")


if __name__ == "__main__":
    main()
