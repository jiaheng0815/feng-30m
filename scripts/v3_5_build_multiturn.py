def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "v3_5b" / "mt_convs.jsonl"))
    ap.add_argument("--seed", type=int, default=20261011)
    ap.add_argument("--n", type=int, default=2000, help="组合生成的多轮对话条数")
    args = ap.parse_args()
    rng = random.Random(args.seed)

    convs = []
    # 组合式生成：情绪 × 回应说法 × 后续话题（避免只背 52 条模板）
    follow_ups = [
        ("今天适合做点什么？", "可以出门走走，或者把想做的事写下来，挑一件先开始。"),
        ("对了，明天会下雨吗？", "我查不到实时天气，出门前看一下天气应用更准。"),
        ("帮我数一下 3 加 4", "3 加 4 等于 7。"),
        ("推荐一首歌吧", "可以听听《海阔天空》，听起来很有劲。"),
        ("你能陪我说说话吗？", "当然，我在呢。想聊什么都可以。"),
        ("谢谢你", "不客气，能帮上忙就好。"),
        ("今天几号？", "我没有实时日期，你看一下设备上的日历更准。"),
        ("讲个笑话吧", "有只猫掉进了纸箱，它想了半天，说：这箱子挺舒服。"),
        ("我该怎么办？", "先说说什么事让你为难，我们一起理一理。"),
        ("我还想聊聊", "好啊，你慢慢说，我不着急。"),
        ("你能写代码吗？", "简单的可以，比如把一串数字排序；复杂的我还做不好。"),
        ("你会唱歌吗？", "我不会唱歌，不过可以帮你把歌词写出来。"),
    ]
    for mood, replies, nxt in MOODS:
        for rep in replies:                     # 每种情绪 × 每种回应说法 = 一条对话
            convs.append([("user", mood), ("assistant", rep),
                          ("user", nxt[0]), ("assistant", nxt[1])])
        # 变化：情绪后面接一个完全无关的小问题（逼模型换话题，而不是复读）
        convs.append([("user", mood), ("assistant", rng.choice(replies)),
                      ("user", "对了，明天会下雨吗？"),
                      ("assistant", "我查不到实时天气，你出门前看一下天气应用更准。")])
        convs.append([("user", mood), ("assistant", rng.choice(replies)),
                      ("user", "帮我数一下 3 加 4"), ("assistant", "3 加 4 等于 7。")])
        for fu, ans in follow_ups:              # 情绪 × 12 种后续话题
            convs.append([("user", mood), ("assistant", rep),
                          ("user", fu), ("assistant", ans)])
            convs.append([("user", mood), ("assistant", rep),
                          ("user", fu), ("assistant", ans),
                          ("user", "谢谢你"), ("assistant", "不客气，还有想问的随时说。")])
    convs += TOPIC_CHAIN
    convs += TOPIC_CHAIN                      # 话题链多来一遍
    while len(convs) < args.n:                # 用组合继续补足到目标条数
        mood, replies, nxt = rng.choice(MOODS)
        fu, ans = rng.choice(follow_ups)
        convs.append([("user", rng.choice([mood, mood + "，真的"]),
                       ), ("assistant", rng.choice(replies)),
                      ("user", fu), ("assistant", ans)])

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as f:
        for c in convs:
            f.write(json.dumps({"messages": [{"role": r, "content": t} for r, t in c]},
                               ensure_ascii=False) + "\n")
    print(f"多轮对话 {len(convs)} 条 -> {out}")


if __name__ == "__main__":
    main()
