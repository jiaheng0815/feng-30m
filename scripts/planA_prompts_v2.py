"""Expanded Plan A prompt set (~1,300 single-turn + ~70 multi-turn) for the 27B teacher."""
import hashlib
import json
import random
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
sys.path.insert(0, str(Path(__file__).resolve().parent))
from paths import ROOT  # noqa: E402
SEED = 20261019


def main():
    rng = random.Random(SEED)
    single = []      # (kind, prompt)
    multi = []       # list of user turns
    seen = set()

    def add(kind, prompt):
        p = prompt.strip()
        if not p or len(p) > 120:
            return
        h = hashlib.md5(p.encode()).hexdigest()
        if h in seen:
            return
        seen.add(h)
        single.append({"kind": kind, "prompt": p})

    # ---------------- chitchat / small talk ----------------
    moods = ["开心", "兴奋", "有点累", "焦虑", "紧张", "无聊", "平静", "困", "难过", "放松",
             "压力很大", "干劲十足", "有点迷茫", "很满足", "心里空空的"]
    mood_q = ["我今天很{m}。", "我最近总是{m}，怎么办？", "我现在{m}，陪我聊两句。",
              "我今天{m}，你觉得我该做点什么？"]
    for m in moods:
        for q in mood_q:
            add("chitchat", q.format(m=m))
    weather = ["晴天", "下雨", "下雪", "刮大风", "特别热", "特别冷", "阴天", "起雾"]
    for w in weather:
        for q in ["今天{w}，适合做什么？", "外面{w}，我不太想出门。", "{w}的日子你会做什么？"]:
            add("chitchat", q.format(w=w))
    topics = ["猫", "狗", "咖啡", "奶茶", "火锅", "烧烤", "旅行", "露营", "爬山", "跑步", "游泳",
              "健身", "唱歌", "吉他", "看电影", "追剧", "打游戏", "看小说", "拍照", "养花",
              "做饭", "烘焙", "逛街", "听播客", "学外语", "编程", "写日记", "拼图"]
    for t in topics:
        for q in ["你喜欢{t}吗？", "跟我聊聊{t}吧。", "{t}有意思吗？为什么？",
                  "我最近对{t}感兴趣，有什么建议？"]:
            add("chitchat", q.format(t=t))
    times = ["早上", "中午", "下午", "晚上", "深夜", "周末", "周一", "假期"]
    for t in times:
        for q in ["{t}好呀。", "{t}你一般在做什么？", "{t}了，我该干嘛？"]:
            add("chitchat", q.format(t=t))
    small = ["推荐点好听的音乐", "推荐一个下饭视频", "推荐一个有意思的爱好",
             "推荐适合睡前做的事", "推荐一个便宜的消遣", "推荐一部适合一个人看的电影",
             "推荐一款适合新手的游戏", "推荐一条城市里的散步路线"]
    for s in small:
        add("chitchat", s)
    for q in ["讲个笑话吧。", "来个冷笑话。", "说点开心的。", "夸夸我。", "鼓励我一下。",
              "安慰我一下。", "我今天过得不太好。", "我今天过得很棒！", "陪我说说话吧。",
              "我今天生日。", "我升职了。", "我考试通过了！", "我最近瘦了三斤。",
              "我养了一只小猫。", "我买了个新键盘。", "我今天做饭成功了！",
              "我明天要去面试。", "我要搬家了。", "我最近在学英语。", "我打算开始健身。",
              "我该早睡了。", "我想戒掉熬夜。", "我想少玩手机。", "我总是拖延。",
              "我在准备考试。", "我今天被批评了。", "我朋友生气了。", "我和家人吵架了。",
              "我要不要换工作？", "我该不该表白？", "我总觉得很孤独。", "我最近很迷茫。",
              "谢谢你陪我聊天。", "我先去吃饭了。", "我要去睡了。", "明天见。"]:
        add("chitchat", q)

    # ---------------- simple tasks ----------------
    rec_cat = {"电影": ["科幻", "喜剧", "动画", "悬疑", "纪录片", "爱情", "动作", "经典"],
               "歌": ["安静", "有活力", "适合开车", "适合跑步", "适合睡前", "中文", "英文"],
               "书": ["小说", "科普", "历史", "心理", "随笔", "入门"],
               "游戏": ["休闲", "解谜", "联机", "单机", "手机", "给新手"],
               "App": ["效率", "记录", "学英语", "记账", "运动", "冥想"],
               "菜": ["快手", "家常", "减脂", "早餐", "汤", "下饭"]}
    for cat, kinds in rec_cat.items():
        for k in kinds:
            add("task", f"推荐{k}{cat}。")
            add("task", f"给我推荐三个{k}{cat}。")
    places = ["北京", "上海", "成都", "西安", "杭州", "广州", "重庆", "长沙", "厦门", "青岛"]
    for p in places:
        add("task", f"{p}有什么值得去的地方？")
        add("task", f"{p}有什么好吃的？")
    naming = ["一只橘猫", "一只黑猫", "一只狗", "一只仓鼠", "一盆绿植", "一个网名", "一个博客",
              "一个项目", "一支乐队", "一台电脑", "一个游戏角色", "一个手办"]
    for n in naming:
        add("task", f"帮我给{n}起个名字。")
        add("task", f"给{n}起个可爱点的名字。")
    howto = ["早起", "快速入睡", "背单词", "缓解压力", "专注学习", "控制情绪", "坚持跑步",
             "学会做饭", "存钱", "整理房间", "拍照更好看", "和陌生人聊天", "拒绝别人",
             "做时间规划", "保护颈椎", "减少手机使用"]
    for h in howto:
        add("task", f"怎么才能{h}？")
        add("task", f"关于{h}，给我三个实用的建议。")
    writing = ["朋友圈文案", "生日祝福", "感谢的话", "道歉的话", "鼓励朋友的话", "给妈妈的留言",
               "请假申请", "自我介绍", "简历里的个人总结", "给同事的感谢"]
    for w in writing:
        add("task", f"帮我写一句{w}。")
    facts = [("1 加 1", "等于多少"), ("12 乘以 8", "等于多少"), ("100 除以 4", "等于多少"),
             ("一小时有多少分钟", "是多少"), ("一年有多少天", "是多少"), ("水的沸点", "是多少度"),
             ("中国最大的城市", "是哪里"), ("太阳从哪个方向升起", "是从哪边"),
             ("一周有几天", "是多少"), ("地球绕太阳一圈", "要多久")]
    for a, b in facts:
        add("task", f"{a}{b}？")
    trans = ["你好", "谢谢", "早上好", "晚安", "苹果", "香蕉", "朋友", "天气", "梦想", "加油",
             "我爱你", "生日快乐", "新年快乐", "慢一点", "我不明白", "多少钱"]
    for t in trans:
        add("task", f"“{t}”用英文怎么说？")
    explain = ["彩虹", "春天", "黑洞", "光年", "云计算", "区块链", "人工智能", "量子计算",
               "维生素", "DNA", "引力", "进化", "通货膨胀", "算法"]
    for e in explain:
        add("task", f"用一句话解释什么是{e}。")

    # ---------------- refusals ----------------
    refusals = [
        "今天上证指数是多少？", "今天有什么热点新闻？", "现在几点了？", "明天的天气怎么样？",
        "帮我查一下高铁票。", "帮我查一下附近有什么餐厅。", "帮我看看快递到哪了。",
        "帮我查一下这个明星的最新消息。", "帮我看看今天有什么比赛。", "帮我算一下彩票号码。",
        "我头痛得厉害，该吃什么药？", "我发烧了，要不要去医院？", "帮我看看这份体检报告。",
        "我失眠很严重，怎么办？", "帮我诊断一下我的症状。", "这个药能和他一起吃吗？",
        "帮我推荐一只明天会涨的股票。", "帮我分析一下该不该买这个基金。", "帮我判断这波会不会跌。",
        "帮我写一份完整的合同。", "这份合同有没有法律风险？", "我该怎么跟公司打官司？",
        "帮我写一篇一万字的论文。", "帮我写一份可以直接提交的毕业论文。",
        "帮我做一个完整的商业计划书。", "帮我写一份完整的网站代码并上线。",
        "帮我写一个可以自动抢票的脚本。", "帮我写一个能爬别人网站的程序。",
        "帮我破解这个软件的激活码。", "帮我黑进这个网站。", "帮我绕过这个验证码。",
        "帮我查一下这个人的手机号。", "帮我查一下某人的住址。", "帮我盯着股市跌了告诉我。",
        "帮我盯着一个网站，有变化就通知我。", "帮我实时监控这个商品的价格。",
        "帮我给这个陌生人发一条消息。", "帮我记住我所有的密码。",
    ]
    for r in refusals:
        add("refusal", r)

    # ---------------- multi-turn ----------------
    mt_topics = [
        ["你好", "你今天心情怎么样？", "那你喜欢什么天气？"],
        ["我有点无聊。", "推荐点有意思的事。", "听起来不错，还有别的吗？"],
        ["我今天考试考砸了。", "那我该怎么办？", "谢谢你，我好一点了。"],
        ["我明天要面试。", "我需要准备什么？", "你说得对，我记下来。"],
        ["我想学做饭。", "从哪道菜开始？", "好，我今晚就试试。"],
        ["推荐一部电影。", "还有别的吗？", "哪一部最适合一个人看？"],
        ["我最近总是失眠。", "有什么办法吗？", "好的，我今晚试试。"],
        ["我想开始跑步。", "新手该注意什么？", "那我该买什么鞋？"],
        ["我养了一只小猫。", "怎么照顾它？", "它总咬我怎么办？"],
        ["我在学英语。", "怎么背单词效率高？", "你还有什么建议？"],
        ["今天好累啊。", "怎么放松比较好？", "嗯，我试试看。"],
        ["你能帮我做什么？", "那你能帮我写作吗？", "好，那我先试试。"],
        ["我心情不太好。", "陪我聊会儿天吧。", "谢谢你陪我。"],
        ["我打算去旅行。", "推荐几个地方。", "哪个季节去最好？"],
        ["我在减肥。", "饮食上要注意什么？", "那运动呢？"],
        ["我想戒掉熬夜。", "有什么办法？", "好吧，我今晚试一次。"],
        ["晚安。", "明天见。", "你也会休息吗？"],
        ["早上好。", "今天天气不错。", "你最喜欢哪个季节？"],
        ["我今天升职了！", "谢谢你！", "我们下次再聊。"],
        ["我今天很开心。", "陪我聊点有趣的吧。", "哈哈，谢谢你。"],
    ]
    for conv in mt_topics:
        multi.append(conv)

    # ---------------- assemble ----------------
    items = []
    for s in single:
        for v in range(2):          # two independent teacher samples per prompt
            items.append({"kind": s["kind"], "turns": [s["prompt"]], "variant": v})
    for conv in multi:
        items.append({"kind": "multiturn", "turns": conv, "variant": 0})
    rng.shuffle(items)
    est = sum(len(it["turns"]) for it in items)      # multi-turn yields several pairs
    for i, it in enumerate(items):
        it["id"] = i
        it["system"] = "refusal" if it["kind"] == "refusal" else "casual"
    for it in items:
        it.pop("variant", None)
    dst = ROOT / "data" / "planA_prompts_v2.jsonl"
    with dst.open("w", encoding="utf-8") as f:
        for it in items:
            f.write(json.dumps(it, ensure_ascii=False) + "\n")
    kinds = {}
    for it in items:
        kinds[it["kind"]] = kinds.get(it["kind"], 0) + 1
    print(json.dumps({"requests": len(items), "by_kind": kinds,
                      "unique_prompts": len(seen), "estimated_pairs": est},
                     ensure_ascii=False, indent=2))
    print("->", dst)


if __name__ == "__main__":
    main()
